/** Ссылка на раздел КР с УУР/УДД. */
export interface KrRef {
  section: string;
  grade?: 'A' | 'B' | 'C';
  level?: number;
  /** Иная КР (id из RELATED_GUIDELINES). */
  doc?: string;
}

export function refText(r: KrRef): string {
  const doc = r.doc ? RELATED_GUIDELINES.find((g) => g.id === r.doc)?.title : undefined;
  const base = `${doc ? `КР «${shortDoc(r.doc!)}»` : 'КР'}, ${r.section}`;
  return r.grade ? `${base}; УУР ${r.grade}, УДД ${r.level}` : base;
}

function shortDoc(id: string): string {
  return { aj: 'Маловодие/многоводие', mult: 'Многоплодная беременность', fgr: 'ЗРП', breech: 'Тазовое предлежание' }[id] ?? id;
}

